import adapterCloudflare from '@sveltejs/adapter-cloudflare';
import adapterNode from '@sveltejs/adapter-node';
import { vitePreprocess } from '@sveltejs/vite-plugin-svelte';
import tailwindcss from '@tailwindcss/vite';
import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig } from 'vite';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

function resolveBuildTimeVersions(): { appVersion: string; backendVersion: string } {
	const envAppVersion = process.env.APP_VERSION?.trim();
	if (envAppVersion) {
		return {
			appVersion: envAppVersion,
			backendVersion: process.env.BACKEND_VERSION?.trim() || 'unknown'
		};
	}

	try {
		const pkg = JSON.parse(readFileSync(resolve(import.meta.dirname, 'package.json'), 'utf-8')) as {
			version?: string;
		};
		if (pkg.version) {
			return {
				appVersion: pkg.version,
				backendVersion: process.env.BACKEND_VERSION?.trim() || 'unknown'
			};
		}
	} catch {
		// Use the explicit fallback when package metadata is unavailable.
	}

	return {
		appVersion: 'unknown',
		backendVersion: process.env.BACKEND_VERSION?.trim() || 'unknown'
	};
}

const { appVersion, backendVersion } = resolveBuildTimeVersions();

// Two build targets, one config:
// - default (`npm run build`): adapter-cloudflare -> .svelte-kit/cloudflare,
//   which is what the Cloudflare Pages dashboard build command expects.
// - `SVELTE_ADAPTER=node` (`npm run build:node`, also set by the frontend
//   Dockerfile): adapter-node -> build/index.js so the self-hosted production
//   server (`node build/index.js`) is actually regenerated by a build.
// Without the node target, `npm run build` leaves build/ untouched and
// `node build/index.js` keeps serving whatever artifact is already there.
const adapter =
	process.env.SVELTE_ADAPTER === 'node'
		? adapterNode()
		: adapterCloudflare({
				routes: {
					// Pages redirects HTML assets to extensionless URLs before routing.
					exclude: ['<all>', '/offline', '/pwa-start']
				}
			});

export default defineConfig({
	define: {
		__APP_VERSION__: JSON.stringify(appVersion),
		__BACKEND_VERSION__: JSON.stringify(backendVersion)
	},
	plugins: [
		tailwindcss(),
		sveltekit({
			// Consult https://svelte.dev/docs/kit/integrations
			// for more information about preprocessors
			preprocess: vitePreprocess(),
			paths: { origin: process.env.ORIGIN || undefined },
			adapter
		})
	],
	ssr: { noExternal: ['cookie'] },
	// Sharing the development server over a network (e.g., ngrok)
	server: {
		host: true,
		allowedHosts: true,
		hmr: {
			// Use wss for remote/ngrok, ws for local
			protocol: process.env.REMOTE_DEV ? 'wss' : 'ws',
			clientPort: process.env.REMOTE_DEV ? 443 : undefined
		}
	}
});
